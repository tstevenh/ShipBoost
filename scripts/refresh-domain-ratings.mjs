// Refresh Domain Rating (DR) values from the Ahrefs free DR API.
//
// Updates:
//   - src/content/resources/startup-directories.json  (per-directory dr)
//   - src/content/site-domain-rating.ts               (shipboost.io dr for the badge)
//
// Run:  node scripts/run-with-env.mjs node scripts/refresh-domain-ratings.mjs
// Add --dry to preview changes without writing.
//
// Data usage requires attribution: "Domain Rating by Ahrefs".
// https://ahrefs.com/legal/domain-rating-license
//
// Auth: AHREFS_API_TOKEN (Bearer) is optional until 2026-09-01, required after.
// Without it the unauthenticated free endpoint is used (more likely to 429).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const DRY = process.argv.includes("--dry");
const TOKEN = process.env.AHREFS_API_TOKEN;
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIRS_PATH = join(ROOT, "src/content/resources/startup-directories.json");
const DIRS_UPDATED_AT_PATH = join(
  ROOT,
  "src/content/resources/startup-directories-updated-at.ts",
);
const SITE_DR_PATH = join(ROOT, "src/content/site-domain-rating.ts");
const SITE_DOMAIN = "shipboost.io";
const THROTTLE_MS = 350; // ~3 requests/sec

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function fetchDomainRating(domain, retries = 3) {
  const url = `https://api.ahrefs.com/v3/public/domain-rating-free?target=${encodeURIComponent(
    domain,
  )}&output=json`;
  for (let attempt = 0; attempt <= retries; attempt++) {
    const res = await fetch(url, {
      headers: TOKEN ? { Authorization: `Bearer ${TOKEN}` } : {},
    });
    if (res.status === 429) {
      const wait = 2000 * (attempt + 1);
      console.warn(`\n  429 for ${domain}, backing off ${wait}ms`);
      await sleep(wait);
      continue;
    }
    if (!res.ok) {
      throw new Error(`HTTP ${res.status}`);
    }
    const json = await res.json();
    const dr = json?.domain_rating?.domain_rating;
    if (typeof dr !== "number") {
      throw new Error("no domain_rating in response");
    }
    return Math.round(dr);
  }
  throw new Error("exhausted retries (429)");
}

async function main() {
  if (!TOKEN) {
    console.warn(
      "WARNING: AHREFS_API_TOKEN not set — using the unauthenticated free API " +
        "(works until 2026-09-01, more likely to hit 429s).\n",
    );
  }

  const dirs = JSON.parse(readFileSync(DIRS_PATH, "utf8"));
  const domains = [...new Set(dirs.map((d) => d.domain))];
  console.log(
    `${dirs.length} directories · ${domains.length} unique domains · +${SITE_DOMAIN}\n`,
  );

  const drByDomain = new Map();
  const failed = [];
  for (const domain of domains) {
    try {
      drByDomain.set(domain, await fetchDomainRating(domain));
      process.stdout.write(".");
    } catch (error) {
      failed.push({ domain, error: error.message });
      process.stdout.write("x");
    }
    await sleep(THROTTLE_MS);
  }
  process.stdout.write("\n");

  const changes = [];
  for (const item of dirs) {
    const next = drByDomain.get(item.domain);
    if (typeof next === "number" && next !== item.dr) {
      changes.push({ name: item.name, domain: item.domain, from: item.dr, to: next });
      if (!DRY) item.dr = next;
    }
  }

  let siteDr = null;
  try {
    siteDr = await fetchDomainRating(SITE_DOMAIN);
  } catch (error) {
    console.warn(`Failed to fetch ${SITE_DOMAIN}: ${error.message}`);
  }

  console.log(`\n${changes.length} directory DR change(s):`);
  changes
    .slice(0, 50)
    .forEach((c) => console.log(`  ${c.name} (${c.domain}): ${c.from} → ${c.to}`));
  if (changes.length > 50) console.log(`  ...and ${changes.length - 50} more`);

  if (failed.length) {
    console.log(`\n${failed.length} domain(s) failed (kept existing DR) — review:`);
    failed.forEach((f) => console.log(`  ${f.domain}: ${f.error}`));
  }

  console.log(`\n${SITE_DOMAIN} DR: ${siteDr ?? "(fetch failed, keeping existing)"}`);

  if (DRY) {
    console.log("\n--dry: no files written.");
    return;
  }

  const today = new Date().toISOString().slice(0, 10);

  writeFileSync(DIRS_PATH, JSON.stringify(dirs, null, 2) + "\n");
  console.log(`\nWrote ${DIRS_PATH}`);

  writeFileSync(
    DIRS_UPDATED_AT_PATH,
    "// Auto-generated by scripts/refresh-domain-ratings.mjs — do not edit by hand.\n" +
      "// ISO date (YYYY-MM-DD) the directory Domain Ratings were last refreshed.\n" +
      `export const startupDirectoriesUpdatedAt = "${today}";\n`,
  );
  console.log(`Wrote ${DIRS_UPDATED_AT_PATH}`);

  if (siteDr !== null) {
    const content =
      "// Auto-generated by scripts/refresh-domain-ratings.mjs — do not edit by hand.\n" +
      "// Domain Rating by Ahrefs (https://ahrefs.com/legal/domain-rating-license)\n" +
      "export const siteDomainRating = {\n" +
      `  value: ${siteDr},\n` +
      `  updatedAt: "${today}",\n` +
      "} as const;\n";
    writeFileSync(SITE_DR_PATH, content);
    console.log(`Wrote ${SITE_DR_PATH}`);
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
